/* Leet-Collection dashboard — vanilla JS, no framework, no build step.
   Fetches ./data.json (regenerated by scripts/generate_site.py on every
   push) and renders the hero stats, trophy case, charts, heatmap, and
   filterable problem grid. */

const HLJS_LANG_BY_EXT = {
  py: "python", java: "java", js: "javascript", ts: "typescript",
  cpp: "cpp", cc: "cpp", c: "c", cs: "csharp", go: "go",
  rb: "ruby", rs: "rust", kt: "kotlin", swift: "swift",
};

const DIFF_COLOR = { Easy: "#4fd8b0", Medium: "#f2a93b", Hard: "#f2555a", Unknown: "#5e5876" };

let STATE = { problems: [], achievements: [], filtered: [] };

async function main() {
  let data;
  try {
    const res = await fetch("data.json", { cache: "no-store" });
    data = await res.json();
  } catch (e) {
    document.getElementById("term-output").hidden = false;
    document.getElementById("term-output").textContent =
      "error: could not load data.json — has the build workflow run yet?";
    return;
  }

  STATE.problems = data.problems || [];
  STATE.achievements = data.achievements || [];
  STATE.repo = data.repo;
  STATE.filtered = STATE.problems.slice();

  document.getElementById("footer-generated").textContent =
    "data generated " + new Date(data.generated_at).toLocaleString();
  const repoLink = document.getElementById("footer-repo");
  repoLink.href = `https://github.com/${data.repo}`;

  await runHeroTypewriter();
  renderTrophies();
  renderCharts();
  renderHeatmap();
  populateLanguageFilter();
  wireFilterBar();
  applyFiltersAndRender();
  wireModal();
}

/* ---------------- Hero typewriter ---------------- */
function computeStats() {
  const diff = { Easy: 0, Medium: 0, Hard: 0 };
  const langs = new Set();
  for (const p of STATE.problems) {
    if (diff[p.difficulty] !== undefined) diff[p.difficulty]++;
    (p.languages || []).forEach((l) => langs.add(l));
  }
  return { total: STATE.problems.length, diff, langCount: langs.size };
}

function sleep(ms) { return new Promise((r) => setTimeout(r, ms)); }

async function typeText(el, text, speed = 18) {
  for (let i = 0; i < text.length; i++) {
    el.textContent += text[i];
    if (text[i] !== " ") await sleep(speed);
  }
}

async function runHeroTypewriter() {
  const typedEl = document.getElementById("term-typed");
  const outputEl = document.getElementById("term-output");
  const cursor = document.getElementById("term-cursor");
  const s = computeStats();

  await typeText(typedEl, "./generate_stats.sh --summary");
  await sleep(250);
  cursor.style.display = "none";
  outputEl.hidden = false;
  outputEl.innerHTML =
    `solved:     <span class="stat-num">${s.total}</span> problems\n` +
    `difficulty: <span class="stat-easy">${s.diff.Easy} easy</span> · ` +
    `<span class="stat-med">${s.diff.Medium} medium</span> · ` +
    `<span class="stat-hard">${s.diff.Hard} hard</span>\n` +
    `languages:  <span class="stat-num">${s.langCount}</span>\n` +
    `status:     <span class="stat-easy">up to date ✓</span>`;
}

/* ---------------- Trophy case ---------------- */
function renderTrophies() {
  const row = document.getElementById("trophy-row");
  row.innerHTML = "";
  for (const a of STATE.achievements) {
    const div = document.createElement("div");
    div.className = "trophy" + (a.unlocked ? "" : " locked");
    div.title = a.desc;
    div.innerHTML =
      `<span class="trophy-icon">${a.unlocked ? a.icon : "🔒"}</span>` +
      `<div class="trophy-name">${a.name}</div>`;
    row.appendChild(div);
  }
}

/* ---------------- Charts ---------------- */
function renderCharts() {
  const s = computeStats();

  new Chart(document.getElementById("chart-difficulty"), {
    type: "doughnut",
    data: {
      labels: ["Easy", "Medium", "Hard"],
      datasets: [{ data: [s.diff.Easy, s.diff.Medium, s.diff.Hard],
                   backgroundColor: [DIFF_COLOR.Easy, DIFF_COLOR.Medium, DIFF_COLOR.Hard],
                   borderWidth: 0 }],
    },
    options: {
      plugins: { legend: { labels: { color: "#8b85a3", font: { family: "JetBrains Mono", size: 11 } } },
                 title: { display: true, text: "difficulty", color: "#e9e6f2", font: { family: "JetBrains Mono", size: 12 } } },
    },
  });

  const topicCounts = {};
  for (const p of STATE.problems) for (const t of p.topics || []) topicCounts[t] = (topicCounts[t] || 0) + 1;
  const top = Object.entries(topicCounts).sort((a, b) => b[1] - a[1]).slice(0, 8);

  new Chart(document.getElementById("chart-topics"), {
    type: "bar",
    data: { labels: top.map((t) => t[0]),
            datasets: [{ label: "problems", data: top.map((t) => t[1]), backgroundColor: "#9d8cff" }] },
    options: {
      indexAxis: "y",
      plugins: { legend: { display: false },
                 title: { display: true, text: "top topics", color: "#e9e6f2", font: { family: "JetBrains Mono", size: 12 } } },
      scales: { x: { ticks: { color: "#8b85a3" }, grid: { color: "#2a2638" } },
                y: { ticks: { color: "#8b85a3", font: { family: "JetBrains Mono", size: 11 } }, grid: { display: false } } },
    },
  });
}

/* ---------------- Heatmap ---------------- */
function renderHeatmap() {
  const counts = {};
  for (const p of STATE.problems) if (p.date) counts[p.date] = (counts[p.date] || 0) + 1;

  const el = document.getElementById("heatmap");
  el.innerHTML = "";
  const days = 182; // ~6 months
  const today = new Date();
  const max = Math.max(1, ...Object.values(counts));

  for (let i = days - 1; i >= 0; i--) {
    const d = new Date(today);
    d.setDate(d.getDate() - i);
    const key = d.toISOString().slice(0, 10);
    const c = counts[key] || 0;
    const cell = document.createElement("div");
    cell.className = "heatmap-cell";
    if (c > 0) {
      const alpha = 0.25 + 0.75 * (c / max);
      cell.style.background = `rgba(79, 216, 176, ${alpha.toFixed(2)})`;
    }
    cell.title = `${key}: ${c} solved`;
    el.appendChild(cell);
  }
}

/* ---------------- Filter bar ---------------- */
function populateLanguageFilter() {
  const langs = new Set();
  STATE.problems.forEach((p) => (p.languages || []).forEach((l) => langs.add(l)));
  const sel = document.getElementById("f-language");
  [...langs].sort().forEach((l) => {
    const opt = document.createElement("option");
    opt.value = l; opt.textContent = l.toLowerCase();
    sel.appendChild(opt);
  });
}

function wireFilterBar() {
  ["f-search", "f-difficulty", "f-language", "f-sort"].forEach((id) => {
    document.getElementById(id).addEventListener("input", applyFiltersAndRender);
    document.getElementById(id).addEventListener("change", applyFiltersAndRender);
  });
}

function applyFiltersAndRender() {
  const q = document.getElementById("f-search").value.trim().toLowerCase();
  const diff = document.getElementById("f-difficulty").value;
  const lang = document.getElementById("f-language").value;
  const sort = document.getElementById("f-sort").value;

  let list = STATE.problems.filter((p) => {
    if (diff && p.difficulty !== diff) return false;
    if (lang && !(p.languages || []).includes(lang)) return false;
    if (q) {
      const hay = [p.title, p.slug, ...(p.topics || [])].join(" ").toLowerCase();
      if (!hay.includes(q)) return false;
    }
    return true;
  });

  list.sort((a, b) => {
    if (sort === "number-asc") return a.number - b.number;
    if (sort === "number-desc") return b.number - a.number;
    if (sort === "date-desc") return (b.date || "").localeCompare(a.date || "");
    if (sort === "date-asc") return (a.date || "").localeCompare(b.date || "");
    return 0;
  });

  STATE.filtered = list;
  document.getElementById("result-count").textContent = `${list.length} / ${STATE.problems.length}`;
  renderGrid();
}

/* ---------------- Grid ---------------- */
function renderGrid() {
  const grid = document.getElementById("grid");
  const empty = document.getElementById("empty-state");
  grid.innerHTML = "";

  if (STATE.filtered.length === 0) {
    empty.hidden = false;
    return;
  }
  empty.hidden = true;

  for (const p of STATE.filtered) {
    const card = document.createElement("div");
    card.className = "card";
    const barClass = { Easy: "bar-easy", Medium: "bar-medium", Hard: "bar-hard" }[p.difficulty] || "bar-unknown";
    const topicsHtml = (p.topics || []).slice(0, 4)
      .map((t) => `<span class="tag">${escapeHtml(t)}</span>`).join("");

    card.innerHTML = `
      <div class="card-bar ${barClass}"></div>
      <div class="card-body">
        <div class="card-num">#${p.number}</div>
        <div class="card-title"><a href="${p.leetcode_url}" target="_blank" rel="noopener">${escapeHtml(p.title)}</a></div>
        <div class="tag-row">
          <span class="tag tag-diff-${p.difficulty}">${p.difficulty}</span>
          ${topicsHtml}
        </div>
        <div class="card-footer">
          <span>${p.date || "—"}</span>
          <button type="button" ${p.raw_url ? "" : "disabled"} data-slug="${p.slug}">view code</button>
        </div>
      </div>`;

    const btn = card.querySelector("button");
    if (p.raw_url) btn.addEventListener("click", () => openModal(p));
    grid.appendChild(card);
  }
}

function escapeHtml(s) {
  return String(s).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
}

/* ---------------- Modal / code viewer ---------------- */
function wireModal() {
  document.getElementById("modal-close").addEventListener("click", closeModal);
  document.getElementById("modal-close").addEventListener("keydown", (e) => {
    if (e.key === "Enter" || e.key === " ") closeModal();
  });
  document.getElementById("modal-backdrop").addEventListener("click", (e) => {
    if (e.target.id === "modal-backdrop") closeModal();
  });
  document.addEventListener("keydown", (e) => {
    if (e.key === "Escape") closeModal();
  });
}

async function openModal(p) {
  const backdrop = document.getElementById("modal-backdrop");
  const title = document.getElementById("modal-title");
  const codeEl = document.getElementById("modal-code-content");

  title.textContent = p.solution_file || p.slug;
  codeEl.className = "";
  codeEl.textContent = "loading…";
  backdrop.hidden = false;

  try {
    const res = await fetch(p.raw_url);
    const text = await res.text();
    const ext = (p.solution_file || "").split(".").pop();
    const lang = HLJS_LANG_BY_EXT[ext] || "plaintext";
    codeEl.className = `language-${lang}`;
    codeEl.textContent = text;
    if (window.hljs) window.hljs.highlightElement(codeEl);
  } catch (e) {
    codeEl.textContent = "couldn't load solution file.";
  }
}

function closeModal() {
  document.getElementById("modal-backdrop").hidden = true;
}

main();
